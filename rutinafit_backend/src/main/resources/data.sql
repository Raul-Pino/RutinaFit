DROP TABLE IF EXISTS ejercicios CASCADE;
DROP TABLE IF EXISTS ejercicio_info CASCADE;
DROP TABLE IF EXISTS sesiones CASCADE;
DROP TABLE IF EXISTS rutinas CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;

-- ==========================================
-- 2. CREACIÓN DE TABLAS (SCHEMA)
-- ==========================================

-- Tabla Usuarios
CREATE TABLE usuarios (
    usuario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(255) NOT NULL
);

-- Tabla Rutinas
CREATE TABLE rutinas (
    rutina_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(255),
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_rutina_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(usuario_id)
);

-- Tabla Sesiones
CREATE TABLE sesiones (
    sesion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE,
    rutina_id BIGINT NOT NULL,
    CONSTRAINT fk_sesion_rutina FOREIGN KEY (rutina_id) REFERENCES rutinas(rutina_id)
);

-- Tabla Catálogo de Ejercicios (Info)
CREATE TABLE ejercicio_info (
    ejercicio_info_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo INTEGER NOT NULL, -- 1: Fuerza, 2: Cardio
    nombre VARCHAR(20) NOT NULL,
    descripcion VARCHAR(100)
);

-- Tabla Ejercicios (Los realizados)
CREATE TABLE ejercicios (
    ejercicio_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param1 DOUBLE PRECISION NOT NULL, -- Peso o Distancia
    param2 DOUBLE PRECISION NOT NULL, -- Reps o Tiempo
    sesion_id BIGINT NOT NULL,
    ejercicio_info_id BIGINT NOT NULL,
    CONSTRAINT fk_ejercicio_sesion FOREIGN KEY (sesion_id) REFERENCES sesiones(sesion_id),
    CONSTRAINT fk_ejercicio_info FOREIGN KEY (ejercicio_info_id) REFERENCES ejercicio_info(ejercicio_info_id)
);

